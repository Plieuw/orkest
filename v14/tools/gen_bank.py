"""Orkest's sound bank for FM1 Open: tools/gen_orkest.py's instruments, zones and patches as one binary file
that the firmware reads from the FM1's user flash (written by the installer, see app/orkest_bank.c).

Layout (little-endian; offsets from the start of the bank):
  0    header, 64 B   magic 'ORKB', version 1, header bytes, total bytes, CRC-32 of [64, total), commit word
                      (0xFFFFFFFF in the file; the firmware writes 'CMIT' after a complete upload), counts, table
                      offsets, name
  64   zones          28 B each: data offset, samples, loop start, loop end, rate (/44100, Q16), root (1/16
                      semitone), ADPCM state at the loop start (predictor, index), keys lo..hi, looped
  ..   instruments    20 B each: name[14], first zone, zones, one-shot, 0, level (Q8)
  ..   patches        44 B each: name[14], attack, release, layers, 0, 0, 0,
                      3 x {instrument, keys lo, hi, transpose, level (Q8, 2 B), pan, 0}
  ..   data           IMA ADPCM (two samples a byte, the even one low), 4-byte aligned

  gen_bank.py OUT.bin [--header OUT.h]   (--header: the same bank as a C array, for the host tests)
"""
import struct
import sys
import zlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "tools"))
import gen_orkest as g  # noqa: E402

MAGIC, VERSION, HDR = 0x424B524F, 1, 64
ZONE, INST, PATCH = 28, 20, 44
LIMIT = 520 * 1024              # the user partition (524 KiB) less the settings sector
g.BUDGET = LIMIT


def name14(s):
    b = s.encode("ascii")[:13]
    return b + bytes(14 - len(b))


def bank():
    blob, zones, insts = g.build()
    idx = {d["name"]: i for i, d in enumerate(insts)}
    zt = b"".join(struct.pack("<5I2h4B", z["off"], z["n"], z["ls"], z["le"], z["rate"], z["root16"], z["pred"],
                              z["idx"], z["lo"], z["hi"], 1 if z["looped"] else 0) for z in zones)
    it = b"".join(name14(d["name"]) + struct.pack("<4BH", d["z0"], d["nz"], 1 if d["one"] else 0, 0, g.q8(d["gain"]))
                  for d in insts)
    pt = b""
    for name, a, r, layers in g.PATCHES:
        ls = b""
        for l in layers + [None] * (g.MAXL - len(layers)):
            ls += struct.pack("<3BbHbB", idx[l[0]], l[1], l[2], l[3], g.q8(l[4]), l[5] if len(l) > 5 else 0, 0) \
                if l else bytes(8)
        pt += name14(name) + struct.pack("<6B", a, r, len(layers), 0, 0, 0) + ls
    assert len(zt) == ZONE * len(zones) and len(it) == INST * len(insts) and len(pt) == PATCH * len(g.PATCHES)
    zones_off = HDR
    inst_off = zones_off + len(zt)
    patch_off = inst_off + len(it)
    data_off = (patch_off + len(pt) + 3) & ~3
    body = zt + it + pt + bytes(data_off - patch_off - len(pt)) + bytes(blob)
    total = HDR + len(body)
    if total > LIMIT:
        raise SystemExit(f"gen_bank: {total} B, more than the {LIMIT} B the flash holds")
    crc = zlib.crc32(body) & 0xFFFFFFFF
    hdr = struct.pack("<IHHIII4H5I", MAGIC, VERSION, HDR, total, crc, 0xFFFFFFFF, len(zones), len(insts),
                      len(g.PATCHES), g.MAXL, zones_off, inst_off, patch_off, data_off, len(blob))
    hdr += name14("ORKEST 1")[:16].ljust(16, b"\0")
    hdr = hdr.ljust(HDR, b"\0")
    return hdr + body, len(zones), len(insts), len(g.PATCHES), len(blob)


def main(argv):
    out = Path(argv[0])
    data, nz, ni, np_, nb = bank()
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(data)
    if "--header" in argv:
        h = Path(argv[argv.index("--header") + 1])
        lines = ["/* generated by v14/tools/gen_bank.py: the bank as the host tests load it */",
                 f"static const unsigned char ORK_BANK_FILE[{len(data)}] __attribute__((aligned(4))) = {{"]
        for i in range(0, len(data), 40):
            lines.append("    " + ",".join(map(str, data[i:i + 40])) + ",")
        lines.append("};")
        h.write_text("\n".join(lines) + "\n")
    print(f"bank: {len(data)} B ({nz} zones, {ni} instruments, {np_} patches, {nb} B ADPCM) -> {out}")


if __name__ == "__main__":
    main(sys.argv[1:])
